/**
 * 做页面时的设计规范 —— 由 pageDesignGuide 工具按需发给模型。
 *
 * 为什么不直接塞进 savePage 的工具描述：工具描述每一轮对话都会发给模型，
 * 这份规范有两三千字，平时聊账单、记待办也背着它太浪费。做成一个工具，
 * 只有要做页面的那一轮才读；savePage 在同一轮里没读过就拒收（见 page-tools.ts），
 * 保证不是「写了规范但模型没看」。
 *
 * 起因：用户拍了一道三位数加法的作业题让它做游戏，做出来的是一个
 * 「输入框 + 提交按钮」的计算器 —— 能用，但孩子不会想玩。
 * 普通用户也不会写「要有开始画面、要有音效、要有连击」这种提示词，
 * 这些得由平台替他说。
 *
 * 给模型看的，保持中文（见 docs/开发笔记.md 的多语言一节）。
 */

export const PAGE_TYPES = ['game', 'learning', 'tool', 'report'] as const;
export type PageType = (typeof PAGE_TYPES)[number];

const COMMON = `
# 页面设计规范

目标：做出来的东西要**让人想点开、想用、愿意再用**，不是「能跑就行」。
下面是底线要求，做不到就是没做完。

## 1. 先定视觉主题，再写代码
- 动手前先想一个跟内容相关的主题，用一句话写进 HTML 开头的注释里，例如：
  - 三位数加法闯关 → 「太空探险：每答对一题，火箭升一级」
  - 认识钟表 → 「小熊的一天：帮小熊把闹钟拨对」
  - 家庭支出报告 → 「克制的财经杂志风，深蓝 + 暖橙强调」
- 主题决定配色、插画、文案语气。**别做成默认白底 + 蓝按钮 + 表单**的「后台管理系统风」。

## 2. 配色与排版
- 用 CSS 变量定义一套调色板：背景、表面、主色、强调色、成功、错误、正文、次要文字。
  同时写 @media (prefers-color-scheme: dark) 的深色版。
- 背景可以用柔和的渐变或大色块，让页面有氛围；卡片用圆角（12–24px）+ 柔和阴影。
- 字号要有明显层级：大标题 28–40px 粗体，正文 ≥ 16px，辅助文字 13–14px。
  字体用 system-ui, -apple-system, "PingFang SC", "Microsoft YaHei", sans-serif。
- 数字用 font-variant-numeric: tabular-nums。

## 3. 素材：不能联网，就自己画
- **Emoji 是现成的免费素材**：角色、道具、奖励、图标都可以先用 emoji（🚀⭐🐻🍎🏆），放大到 48–96px 就很有表现力。
- 需要插画、角色、背景装饰时用内联 <svg> 画（简单几何形状组合就够：圆、圆角矩形、路径）。
- 图表用 <svg> 或 <canvas> 自己画，别找库。

## 4. 动效与反馈（这是「好玩」「好用」的关键）
- 所有可点的东西都要有按下反馈：:active { transform: scale(.96) }，transition 150–250ms。
- 状态变化要有过渡，不要生硬地闪现：淡入、滑入、数字滚动。
- 做对 / 完成：弹跳、放大、星星或彩带粒子（用 canvas 或几十个绝对定位的小 div 自己实现）。
- 做错：轻微左右晃动（shake 动画）+ 颜色提示，**不要**用刺眼的大红叉羞辱人。
- 尊重 @media (prefers-reduced-motion: reduce)：关掉大幅动画。

## 5. 声音（可选但加分）
- 用 Web Audio API 现场合成短音效（振荡器 + 包络，几十行代码）：答对叮一声、答错低一声、过关一段上行音阶。
- 必须有静音按钮，默认可以开着；第一次用户点击之后再创建 AudioContext（浏览器要求）。

## 6. 手机优先
- 375px 宽下不能横向滚动；主要按钮放在拇指够得到的下半屏，至少 48px 高。
- 一根手指能完成全部操作：点、拖、滑。不要依赖键盘。
- 需要输入数字时，自己画一个大号数字键盘，比系统键盘好用也好看。

## 7. 完整的流程，不只是中间那一屏
- **开始页**：标题、主题插画、一句话说清怎么玩/怎么用、一个大大的「开始」按钮。
- **进行中**：看得到进度（第几关 / 还剩几题 / 进度条）。
- **结束页**：成绩、评价（星级、称号），「再来一次」按钮。
- 空状态、出错状态也要有样子，不能是一片白。

## 8. 自查清单（写完 HTML 在心里过一遍）
- 第一眼看上去有没有「主题感」，还是像个表单？
- 点每个按钮有没有反馈？做对做错有没有明显不同的反应？
- 手机宽度下有没有东西挤出去？深色模式下字还看得清吗？
- 开始 → 进行 → 结束 → 再来一次，整条路走得通吗？
`;

const GAME = `
# 游戏专项

## 核心循环
目标 → 操作 → 即时反馈 → 奖励 → 更难一点。每一步都要让玩家「感觉到」。

## 必须有
- **关卡或阶段**：3–5 关，难度递增，每关有点新东西（更快、更多干扰项、新规则、限时）。
- **计分与奖励**：分数、连击（连续答对 ×2、×3 并有醒目提示）、星级评价、解锁的称号或收集品。
- **生命或容错**：3 颗心之类，错了扣一颗但不至于马上结束。
- **结束页**：本局成绩、最佳记录（本次打开期间）、「再来一局」。

## 玩法：别只放一个输入框
比「看题 → 在框里打字 → 点提交」更有趣的方式，按合适的选：
- **点选**：从 3–4 个选项气泡里点正确的（选项要有迷惑性：常见错误答案）
- **接住 / 射击**：答案从上方落下或飘过，点中正确的那个
- **配对 / 翻牌**：把题目和答案连起来、翻开两张相同的牌
- **拖拽排序**：把步骤、数字、词语拖到正确位置
- **赛跑 / 爬升**：每答对一题，角色前进一格或火箭升高一截，直观看到进度
能用画面表达的就别用文字：数量用一排图标表示，进度用角色的位置表示。
`;

const LEARNING = `
# 学习 / 错题练习专项

用户发来作业题、错题或课本知识点，要做成练习游戏时，**按下面的顺序做**：

## 第一步：先把题搞对（最重要）
- 在对话回复里先写出：你从图里读到的题目原文、正确答案、关键解题步骤。**自己验算一遍**。
- 看不清、不确定的地方直接说出来，请用户确认，别猜。
- 游戏里教错东西，比不做还糟。

## 第二步：练知识点，不练原题
- 找出这道题背后的知识点（例如「三位数加法的连续进位」「分数的通分」）。
- 出 **8–12 道同类变式题**，由易到难：先是不进位 / 简单情况，再到易错情况。
  原题（或跟原题同样难度的）放在最后一关当「Boss 题」。
- 题目在代码里用数组写死，或者写一个按规则随机生成的函数（生成后自己保证答案正确、难度合适）。

## 第三步：错了要能学会
- 第一次答错：给一句**思路提示**（「个位满十了吗？」），让孩子再试一次。
- 第二次答错：**逐步演示**正确解法（竖式一步步出现、在数轴上跳格子、用方块凑十），再进入下一题。
- 能画出来的就画出来：竖式、数轴、分数饼图、几何图形都用 SVG / HTML 画，比纯文字讲解好懂得多。

## 面向孩子
- 从题目推断年级，语言跟着调整：低年级字大、句子短、多用图形和 emoji。
- 语气始终是鼓励：「差一点！」「再想想个位」，不说「错误」「失败」。
- 结束页做一个**学习小结**：这次练了什么知识点、答对几题、哪几题错过（附正确解法），给一个称号或贴纸奖励。
`;

const TOOL = `
# 小工具专项
- 最常用的那个操作放在最显眼的位置，打开就能用，不需要先看说明。
- 输入即时生效，结果实时更新，不要「填完表单再点计算」。
- 结果要醒目：大号数字 + 一句人话解释（「每月要还 ¥6,820，其中利息占 41%」）。
- 有合理的默认值，用户改一个数就能看到变化。
`;

const REPORT = `
# 数据报告 / 图表专项
- 第一屏回答最重要的问题：2–4 个关键数字做成大号指标卡，每个配一句解读。
- 图表紧跟在结论后面，用来证明结论；坐标轴、单位、图例写清楚，悬停或点击能看到具体数值。
- 配色克制：一个主色系 + 一个强调色标出重点（最大的一项、异常的一项），别用彩虹色。
- 页面在显眼处写「数据截至 YYYY-MM-DD」。
`;

const BY_TYPE: Record<PageType, string> = { game: GAME, learning: GAME + LEARNING, tool: TOOL, report: REPORT };

export function pageDesignGuide(type: PageType) {
  return COMMON + BY_TYPE[type];
}
